import assert from 'node:assert/strict';
import { portfolioSeo } from '../seo.config.js';
const assets = [];
const blank = portfolioSeo();
assert.deepEqual(blank.transformIndexHtml(), []);
blank.generateBundle.call({ emitFile: asset => assets.push(asset) });
assert.equal(assets.length, 1);
assert.equal(assets[0].fileName, 'robots.txt');
assert.ok(!assets[0].source.includes('Sitemap:'));
const configured = portfolioSeo('https://portfolio.example/akash/');
const tags = configured.transformIndexHtml();
assert.equal(tags.find(tag => tag.attrs.rel === 'canonical').attrs.href, 'https://portfolio.example/akash/');
const output = [];
configured.generateBundle.call({ emitFile: asset => output.push(asset) });
assert.ok(output.find(asset => asset.fileName === 'sitemap.xml').source.includes('<loc>https://portfolio.example/akash/</loc>'));
assert.ok(output.find(asset => asset.fileName === 'robots.txt').source.includes('Sitemap: https://portfolio.example/akash/sitemap.xml'));
assert.throws(() => portfolioSeo('javascript:alert(1)'));
assert.throws(() => portfolioSeo('https://portfolio.example/?tracking=1'));
console.log('PASS: no guessed canonical, valid deployment-specific sitemap/robots/Open Graph, and URL validation.');
